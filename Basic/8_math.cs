using System;

namespace HelloWorld {
    class program {
        public static void Main(string[] args) {
            //Max() used to find max from x y  
            Console.WriteLine(Math.Max(422,72));
            
            //min() used to find min from x y
            Console.WriteLine(Math.Min(45,24));
            
            //Sqrt() return square root of x y
            Console.WriteLine(Math.Sqrt(25));
            
            //Abs() give absolute positive value
            Console.WriteLine(Math.Abs(-8.56));
            
            //Round() round the number nearest whole number
            Console.WriteLine(Math.Round(8.4));
        }
    }
}